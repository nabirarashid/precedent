"""M2: ALFWorld track premise test.

Mirrors scripts/premise_family_gold.py on the AgentInstruct/ALFWorld corpus
(336 trajectories, fetched by scripts/fetch_alfworld_corpus.py). Pair types,
from the paper-repo labels:

  A. same task_type, different target_object AND different goal_receptacle
     (candidate GOLD, the paper's hard case)
  B. different task_type (candidate DISTRACTOR)
  C. same task_type, same target_object or same goal_receptacle (easy case)

Per pair: lexical Jaccard on raw action text (same word-set method as the
nebius audits) and weighted n-gram motif similarity over one SignatureStore
of all 336 records. Writes docs/notes/alfworld-premise.md. Measurements only.

Run from the repo root (inside the venv):
    python scripts/premise_alfworld.py
"""

from __future__ import annotations

import json
import os
import random
import statistics
import sys
from collections import Counter
from itertools import combinations
from pathlib import Path

from precedent.alfworld import load_corpus
from precedent.similarity import SignatureStore, motif_similarity

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from audit_nebius_dataset import md_table  # noqa: E402
from audit_nebius_part2 import WORD, above_fraction, hist_label, jaccard  # noqa: E402

N_PAIRS = 200
SEED = 0
DATA = Path(__file__).resolve().parent.parent / "data" / "alfworld"
CORPUS = DATA / "agentinstruct_trajectories.json"
LABELS = DATA / "agentinstruct_task_type_labels.json"
OUT = Path(__file__).resolve().parent.parent / "docs" / "notes" / "alfworld-premise.md"

GROUPS = {
    "A": "same task_type, diff object AND diff receptacle (candidate gold)",
    "B": "different task_type (candidate distractor)",
    "C": "same task_type, same object or receptacle (easy case)",
}


def word_set(traj: dict) -> set[str]:
    """Nebius-audit method on RAW ACTION TEXT: lowercased `\\w+` words >= 3 chars."""
    out: set[str] = set()
    for pair in traj.get("state_action_pairs", []):
        out.update(w for w in WORD.findall((pair.get("action") or "").lower()) if len(w) >= 3)
    return out


def stats_row(label: str, vals: list[float]) -> list[str]:
    return [label, str(len(vals)), f"{statistics.mean(vals):.3f}",
            f"{statistics.median(vals):.3f}", f"{min(vals):.3f}", f"{max(vals):.3f}"]


def hist(scores: dict[str, list[float]]) -> list[str]:
    counts = {g: Counter(hist_label(x) for x in v) for g, v in scores.items()}
    labels = [hist_label(i / 10 + 0.05) for i in range(10)]
    rows = [[lab] + [counts[g].get(lab, 0) for g in scores] for lab in labels]
    return md_table(["score"] + list(scores), [r for r in rows if any(r[1:])])


def main() -> None:
    if not (CORPUS.exists() and LABELS.exists()):
        sys.exit("STOP: data/alfworld/ missing; run scripts/fetch_alfworld_corpus.py first.")

    trajs = json.loads(CORPUS.read_text())["trajectories"]
    labels = {str(l["trajectory_id"]): l for l in json.loads(LABELS.read_text())}
    records = load_corpus(CORPUS, LABELS)
    assert [r.run_id for r in records] == [str(t["task_instance_id"]) for t in trajs]

    store = SignatureStore(records)
    weights = store.idf_weights()
    sigs = store.signatures
    print(f"Store: {len(store)} runs, {len(store.doc_freq)} distinct n-grams")

    wsets = [word_set(t) for t in trajs]
    tt = [labels[r.run_id]["task_type_name"] for r in records]
    to = [labels[r.run_id].get("target_object") for r in records]
    gr = [labels[r.run_id].get("goal_receptacle") for r in records]
    no_gr = sum(1 for g in gr if not g)

    rng = random.Random(SEED)
    pools: dict[str, list[tuple[int, int]]] = {"A": [], "B": [], "C": []}
    unclassified = 0
    for i, j in combinations(range(len(records)), 2):
        if tt[i] != tt[j]:
            pools["B"].append((i, j))
        elif to[i] == to[j] or (gr[i] and gr[i] == gr[j]):
            pools["C"].append((i, j))
        elif gr[i] and gr[j]:  # same task_type, both receptacles known, all differ
            pools["A"].append((i, j))
        else:  # same task_type, objects differ, a goal_receptacle missing
            unclassified += 1
    sampled = {g: rng.sample(p, min(N_PAIRS, len(p))) for g, p in pools.items()}

    lex = {g: [jaccard(wsets[a], wsets[b]) for a, b in pairs] for g, pairs in sampled.items()}
    struct = {g: [motif_similarity(sigs[a], sigs[b], weights) for a, b in pairs]
              for g, pairs in sampled.items()}

    p_struct_a_gt_b = above_fraction(struct["A"], struct["B"])
    p_lex_b_gt_a = above_fraction(lex["B"], lex["A"])

    L: list = [
        "# ALFWorld track premise test — Nov 19, 2026",
        "",
        "*Generated by scripts/premise_alfworld.py over the AgentInstruct/ALFWorld corpus "
        f"({len(records)} trajectories, fetched and sha256-verified by "
        f"scripts/fetch_alfworld_corpus.py; task-type labels from the paper repo). Seed {SEED}. "
        "Measurements only; no design decisions.*",
        "",
        "Premise under test: gold = same task type with different target_object AND different "
        "goal_receptacle (the paper's hard case); distractor = different task type. The design "
        "works if structure separates A from B while lexical overlap within A is low (different "
        "objects = different words).",
        "",
        "## 1. Corpus and signatures",
        "",
        f"336 trajectories, 6 task types: "
        + ", ".join(f"`{t}` ({c})" for t, c in Counter(tt).most_common()) + ".",
        "",
        f"Canonical tokens are action verbs only (object/receptacle quarantined as SURFACE args): "
        f"{len(store.doc_freq):,} distinct n-grams over {len(store)} signatures. "
        f"{no_gr} labels (all `look_at_obj_in_light`) have no goal_receptacle: those rows can "
        "join B (different type) and C via same-object, but not A, which requires both "
        "receptacles known and different.",
        "",
        "## 2. Pair pools",
        "",
        md_table(["type", "", "possible pairs", "sampled"],
                 [[g, GROUPS[g], f"{len(pools[g]):,}", len(sampled[g])] for g in "ABC"]),
        "",
        f"(Same-type pairs with differing objects but a missing goal_receptacle, in no pool: "
        f"{unclassified:,}.)",
        "",
        "## 3. Lexical overlap (Jaccard on raw action text, words >= 3 chars)",
        "",
        md_table(["type", "pairs", "mean", "median", "min", "max"],
                 [stats_row(g, lex[g]) for g in "ABC"]),
        "",
        hist(lex),
        "",
        "## 4. Structural similarity (weighted n-gram motif score, similarity.py as shipped)",
        "",
        md_table(["type", "pairs", "mean", "median", "min", "max"],
                 [stats_row(g, struct[g]) for g in "ABC"]),
        "",
        hist(struct),
        "",
        "## 5. Separations",
        "",
        "P(x > y) over all sampled cross-pairs; ties count half. 0.5 = no separation.",
        "",
        md_table(["comparison", "P", "mean gap"], [
            ["**structural: A > B** (signal exists if > 0.5)", f"{p_struct_a_gt_b:.3f}",
             f"mean(A) − mean(B) = {statistics.mean(struct['A']) - statistics.mean(struct['B']):+.3f}"],
            ["**lexical: B > A** (trap works if >= 0.5-ish: gold not lexically privileged)",
             f"{p_lex_b_gt_a:.3f}",
             f"mean(A) − mean(B) = {statistics.mean(lex['A']) - statistics.mean(lex['B']):+.3f}"],
            ["structural: A > C", f"{above_fraction(struct['A'], struct['C']):.3f}",
             f"{statistics.mean(struct['A']) - statistics.mean(struct['C']):+.3f}"],
            ["lexical: A > C", f"{above_fraction(lex['A'], lex['C']):.3f}",
             f"{statistics.mean(lex['A']) - statistics.mean(lex['C']):+.3f}"],
            ["structural: C > B", f"{above_fraction(struct['C'], struct['B']):.3f}",
             f"{statistics.mean(struct['C']) - statistics.mean(struct['B']):+.3f}"],
            ["lexical: C > B", f"{above_fraction(lex['C'], lex['B']):.3f}",
             f"{statistics.mean(lex['C']) - statistics.mean(lex['B']):+.3f}"],
        ]),
        "",
        "## Verdict",
        "",
        f"**Structural separation of A from B: "
        f"{'holds' if p_struct_a_gt_b > 0.5 else 'does not hold'}.** "
        f"P(structural: A > B) = {p_struct_a_gt_b:.3f}; mean motif score A = "
        f"{statistics.mean(struct['A']):.3f}, B = {statistics.mean(struct['B']):.3f} "
        f"(gap {statistics.mean(struct['A']) - statistics.mean(struct['B']):+.3f}). "
        f"**Lexical position of gold: P(lexical: B > A) = {p_lex_b_gt_a:.3f}**; mean Jaccard "
        f"A = {statistics.mean(lex['A']):.3f}, B = {statistics.mean(lex['B']):.3f} "
        f"(gap {statistics.mean(lex['A']) - statistics.mean(lex['B']):+.3f}). "
        f"A-vs-C: structural {statistics.mean(struct['A']) - statistics.mean(struct['C']):+.3f} "
        f"(P = {above_fraction(struct['A'], struct['C']):.3f}), lexical "
        f"{statistics.mean(lex['A']) - statistics.mean(lex['C']):+.3f} "
        f"(P = {above_fraction(lex['A'], lex['C']):.3f}).",
        "",
    ]
    lines: list[str] = []
    for x in L:
        lines.extend(x if isinstance(x, list) else [x])
    OUT.write_text("\n".join(lines) + "\n")
    print("\n".join(lines[lines.index("## 2. Pair pools"):]))
    print(f"\nWrote {OUT}")


if __name__ == "__main__":
    main()
    sys.stdout.flush()
    os._exit(0)
