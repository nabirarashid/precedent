"""M2: run benchmark track 1 (ALFWorld) and write docs/results/track1-v0.md.

Design of record: docs/design/benchmark-design.md. Requires data/alfworld/
(scripts/fetch_alfworld_corpus.py). Numbers only; the single narrative line
allowed is which system ranked first on the low-overlap bucket.

Run from the repo root (inside the venv):
    python scripts/run_track1.py
"""

from __future__ import annotations

import json
import os
import statistics
import sys
from pathlib import Path

from precedent.alfworld import load_corpus
from precedent.benchmark import (
    bootstrap_ci,
    build_track1_items,
    make_bm25,
    make_minilm,
    make_rerank,
    make_structural,
    mean_word_overlap,
    pull_rate,
    recall_at_k,
    reciprocal_rank,
    trajectory_text,
)
from precedent.similarity import SignatureStore

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from audit_nebius_dataset import md_table  # noqa: E402

SEED = 0
ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data" / "alfworld"
CORPUS = DATA / "agentinstruct_trajectories.json"
LABELS = DATA / "agentinstruct_task_type_labels.json"
ITEMS_OUT = ROOT / "data" / "benchmark" / "track1_items.json"
OUT = ROOT / "docs" / "results" / "track1-v0.md"
K_VALUES = (1, 5, 10)
N_BUCKETS = 3


def dist(sizes: list[int]) -> str:
    return (f"min {min(sizes)}, median {statistics.median(sorted(sizes))}, "
            f"mean {statistics.mean(sizes):.1f}, max {max(sizes)}")


def cell(vals: list[float]) -> str:
    lo, hi = bootstrap_ci(vals, seed=SEED)
    return f"{statistics.mean(vals):.3f} [{lo:.3f}, {hi:.3f}]"


def main() -> None:
    if not (CORPUS.exists() and LABELS.exists()):
        sys.exit("STOP: data/alfworld/ missing; run scripts/fetch_alfworld_corpus.py first.")

    records = load_corpus(CORPUS, LABELS)
    trajs = json.loads(CORPUS.read_text())["trajectories"]
    texts = {str(t["task_instance_id"]): trajectory_text(t) for t in trajs}
    store = SignatureStore(records)

    items = build_track1_items(CORPUS, LABELS, ITEMS_OUT)
    queries = [i for i in items if i.eligible]
    print(f"Items: {len(items)} total, {len(queries)} eligible queries -> {ITEMS_OUT}")
    print(f"  gold-set sizes: {dist([len(q.gold) for q in queries])}")
    print(f"  doppelganger-set sizes: {dist([len(q.doppelgangers) for q in queries])}")

    ids = [r.run_id for r in records]
    systems: dict[str, object] = {"structural": make_structural(records, store)}
    systems["bm25"] = make_bm25(ids, texts)
    minilm_note = None
    try:
        systems["minilm"] = make_minilm(ids, texts)
    except Exception as e:  # install or model download failed: continue without
        minilm_note = f"minilm unavailable ({type(e).__name__}: {e}); other systems reported."
        print(f"NOTE: {minilm_note}")
    systems["structural+bm25 rerank"] = make_rerank(systems["structural"], texts)

    rankings = {name: {q.query_id: sys_fn(q.query_id) for q in queries}
                for name, sys_fn in systems.items()}

    # per-query metric values per system
    recall = {name: {k: [recall_at_k(rk[q.query_id], q.gold, k) for q in queries]
                     for k in K_VALUES} for name, rk in rankings.items()}
    mrr = {name: [reciprocal_rank(rk[q.query_id], q.gold) for q in queries]
           for name, rk in rankings.items()}
    pull = {name: [pull_rate(rk[q.query_id], q.doppelgangers, k=10) for q in queries]
            for name, rk in rankings.items()}

    chance_recall = {k: statistics.mean(q.chance[f"recall@{k}"] for q in queries)
                     for k in K_VALUES}
    chance_mrr_v = statistics.mean(q.chance["mrr"] for q in queries)
    chance_pull = statistics.mean(len(q.doppelgangers) / q.n_candidates for q in queries)

    # lexical-control split: bucket queries by mean full-text overlap with gold
    overlap = {q.query_id: mean_word_overlap(texts[q.query_id],
                                             [texts[g] for g in q.gold]) for q in queries}
    ordered = sorted(queries, key=lambda q: (overlap[q.query_id], q.query_id))
    buckets = [ordered[round(b * len(ordered) / N_BUCKETS):
                       round((b + 1) * len(ordered) / N_BUCKETS)] for b in range(N_BUCKETS)]
    bucket_names = ["low overlap", "mid overlap", "high overlap"]

    def bucket_mrr(name: str, bucket) -> list[float]:
        return [reciprocal_rank(rankings[name][q.query_id], q.gold) for q in bucket]

    low_rank = sorted(systems, key=lambda n: -statistics.mean(bucket_mrr(n, buckets[0])))

    L: list = [
        "# Track 1 (ALFWorld) — v0 results",
        "",
        f"*Generated by scripts/run_track1.py per docs/design/benchmark-design.md. "
        f"N = {len(queries)} queries over a {len(records)}-trajectory store "
        f"({len(items) - len(queries)} incomplete-label trajectories are candidates only). "
        f"Bootstrap: 1,000 resamples over queries, seed {SEED}, percentile 95% CIs. "
        "recall@k = fraction of queries with at least one gold in the top k; chance rows are "
        "exact hypergeometric expectations aggregated over queries. Values rounded to 3 decimals.*",
        "",
        *([f"*{minilm_note}*", ""] if minilm_note else []),
        "## Recall@k",
        "",
        md_table(["system"] + [f"recall@{k}" for k in K_VALUES],
                 [[name] + [cell(recall[name][k]) for k in K_VALUES] for name in systems]
                 + [["chance"] + [f"{chance_recall[k]:.3f}" for k in K_VALUES]]),
        "",
        "## MRR",
        "",
        md_table(["system", "MRR"],
                 [[name, cell(mrr[name])] for name in systems]
                 + [["chance", f"{chance_mrr_v:.3f}"]]),
        "",
        "## Doppelganger pull rate (fraction of top-10)",
        "",
        md_table(["system", "pull rate"],
                 [[name, cell(pull[name])] for name in systems]
                 + [["chance", f"{chance_pull:.3f}"]]),
        "",
        "## Lexical-control split (MRR by query bucket)",
        "",
        f"Queries bucketed into terciles by their gold set's mean full-text Jaccard overlap "
        f"with the query (bucket sizes: {', '.join(str(len(b)) for b in buckets)}; "
        f"overlap ranges: "
        + "; ".join(f"{bn} {overlap[b[0].query_id]:.3f}-{overlap[b[-1].query_id]:.3f}"
                    for bn, b in zip(bucket_names, buckets)) + ").",
        "",
        md_table(["system"] + bucket_names,
                 [[name] + [cell(bucket_mrr(name, b)) for b in buckets] for name in systems]
                 + [["chance"] + [f"{statistics.mean(q.chance['mrr'] for q in b):.3f}"
                                  for b in buckets]]),
        "",
        f"On the low-overlap bucket, `{low_rank[0]}` ranked first by MRR.",
        "",
    ]
    lines: list[str] = []
    for x in L:
        lines.extend(x if isinstance(x, list) else [x])
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    print(f"\nWrote {OUT}")


if __name__ == "__main__":
    main()
    sys.stdout.flush()
    os._exit(0)
