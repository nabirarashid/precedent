"""M1 hand-check: build the 20-run review sheet for the canonicalizer.

Streams the first 20 SWE-smith trajectories (tool split), canonicalizes them
with the library, and writes docs/notes/handcheck-20.md: per run, the
signature plus an audit table pairing each canonical token with the raw
evidence it was derived from (tool name + discriminator arg, or the first 80
chars of the bash command; never model text or observations).

Run from the repo root (inside the venv):
    python scripts/make_handcheck.py
"""

from __future__ import annotations

import os
import sys
from collections import Counter
from itertools import islice
from pathlib import Path

from datasets import load_dataset

from precedent.canonicalize import _discriminator, build_signature, canonical_tool
from precedent.records import Step, StepKind

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from load_sample_traces import to_trace_record  # noqa: E402  (reuse the ingest path)

N = 20
OUT = Path(__file__).resolve().parent.parent / "docs" / "notes" / "handcheck-20.md"

GUIDE = """\
> **Reviewer guide.** A signature is *faithful* when every canonical token correctly names what the agent did at that step.
> Check each audit row: the token must match the raw evidence, and must not be misled by a sub-action, a pipe, or a compound command (`&&`, `;`, `||`).
> Tick "signature faithful" only if every row passes.
> For each failure, write the step number and what the token should have been on the notes line, e.g. `#7: bash.sort → should be bash.find`.
> Raw evidence is tool name + discriminator arg, or the first 80 chars of the bash command; model text and observations are deliberately not shown.
"""


def short_id(run_id: str) -> str:
    return run_id if len(run_id) <= 40 else run_id[:37] + "..."


def raw_evidence(step: Step) -> str:
    """Only what canonical_tool reads: tool name + discriminator, or the bash command."""
    name = step.tool_name or "?"
    if name == "bash":
        cmd = " ".join(str(step.arg_values.get("command", "")).split())  # flatten newlines
        return f"bash: {cmd[:80]}" + ("…" if len(cmd) > 80 else "")
    disc = _discriminator(name)
    if disc is not None:
        return f"{name}: {disc}={step.arg_values.get(disc, '?')}"
    return name


def md_code(text: str) -> str:
    """Code span safe inside a GFM table cell."""
    text = text.replace("|", "\\|")
    fence = "``" if "`" in text else "`"
    return f"{fence} {text} {fence}" if fence == "``" else f"`{text}`"


def main() -> None:
    print(f"Streaming first {N} rows of SWE-bench/SWE-smith-trajectories (tool split) ...")
    stream = load_dataset("SWE-bench/SWE-smith-trajectories", split="tool", streaming=True)
    rows = list(islice(stream, N))

    lines = ["# M1 hand-check: 20 SWE-smith runs", "",
             "*Generated by scripts/make_handcheck.py. Pending human review.*", "", GUIDE]
    totals: Counter = Counter()

    for i, row in enumerate(rows, 1):
        rec = to_trace_record(row, i - 1)
        sig = build_signature(rec)
        totals.update(sig.motif_counts())
        tool_calls = [s for s in rec.steps if s.kind == StepKind.TOOL_CALL]
        one_line = " → ".join(sig.canonical_steps)

        print(f"\n[{i:02d}] {sig.run_id} ({sig.outcome_label.value}, {sig.tool_call_count} calls)")
        print(f"     {one_line}")

        lines += [
            f"## {i:02d}. {short_id(sig.run_id)}", "",
            f"instance: `{rec.task_id}` · outcome: **{sig.outcome_label.value}** · "
            f"{sig.step_count} steps / {sig.tool_call_count} tool calls", "",
            f"**Signature:** {one_line}", "",
            "| # | canonical token | raw evidence |",
            "|---|---|---|",
        ]
        for n, step in enumerate(tool_calls, 1):
            lines.append(f"| {n} | {md_code(canonical_tool(step))} | {md_code(raw_evidence(step))} |")
        lines += ["", "- [ ] signature faithful", "- [ ] notes:", ""]

    total = sum(totals.values())
    freq = ["## Canonical token frequencies (all 20 runs)", "",
            f"{total} tool calls, {len(totals)} distinct tokens. Input to the M2 structural-stopword discussion.", "",
            "| token | count | share |", "|---|---|---|"]
    freq += [f"| {md_code(t)} | {c} | {c / total:.1%} |" for t, c in totals.most_common()]
    lines += freq

    OUT.write_text("\n".join(lines) + "\n")

    print(f"\n=== TOKEN FREQUENCIES ({total} calls, {len(totals)} distinct) ===")
    for t, c in totals.most_common():
        print(f"{c:5d}  {c / total:6.1%}  {t}")
    print(f"\nWrote {OUT}")


if __name__ == "__main__":
    main()
    sys.stdout.flush()  # os._exit skips buffer flushing when stdout is piped
    os._exit(0)  # datasets streaming can hang on connection cleanup
